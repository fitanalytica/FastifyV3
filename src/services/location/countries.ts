export type CountryCode = keyof typeof countries;

/** A code from the list, upper case (`dk` is not one: normalise it first). An own-property check, so `constructor` and the like are not countries. */
export const isCountryCode = (code: string): code is CountryCode => Object.prototype.hasOwnProperty.call(countries, code);

/** The name of a country by its code, in any case, or `null` for no code or one that is not in the list. */
export function countryName(code: string | null | undefined): string | null {
  const iso = (code ?? '').trim().toUpperCase();
  return isCountryCode(iso) ? countries[iso] : null;
}
